async def seed_all_lessons():
    await init_db()

    async with AsyncSessionLocal() as session:
        # 1. Ensure default local user exists
        user_res = await session.execute(select(User).order_by(User.id.asc()).limit(1))
        user = user_res.scalar_one_or_none()
        if user is None:
            user = User(
                telegram_id=1,
                username="student",
                first_name="Student",
                cefr_level="B1",
                active_card_types=list(ALL_CARD_TYPES),
            )
            session.add(user)
            await session.flush()
        else:
            user.active_card_types = list(ALL_CARD_TYPES)
            await session.flush()

        total_words = 0
        total_cards = 0

        # Export list for frontend
        export_lessons = []

        for lesson_data in LESSONS_DATA:
            lesson_id = lesson_data["lesson_id"]
            title = lesson_data["title"]

            # Ensure source
            source_res = await session.execute(
                select(Source).where(Source.user_id == user.id, Source.title == title)
            )
            source = source_res.scalar_one_or_none()
            if source is None:
                source = Source(user_id=user.id, title=title, source_type="curriculum")
                session.add(source)
                await session.flush()

            lesson_items_export = []

            for item in lesson_data["items"]:
                norm = normalize_text(item["lemma"])
                word_res = await session.execute(select(Word).where(Word.normalized == norm))
                word = word_res.scalar_one_or_none()

                if word is None:
                    word = Word(
                        lemma=item["lemma"],
                        normalized=norm,
                        language="en",
                        transcription=item["transcription"],
                        part_of_speech=item["part_of_speech"],
                        cefr_level=item["cefr_level"],
                        translation_ru=item["translation_ru"],
                        collocations=item["collocations"],
                        grammar_note=item["grammar_note"],
                    )
                    session.add(word)
                    await session.flush()
                    total_words += 1
                else:
                    word.translation_ru = item["translation_ru"]
                    word.transcription = item["transcription"]
                    word.part_of_speech = item["part_of_speech"]
                    word.cefr_level = item["cefr_level"]
                    word.collocations = item["collocations"]
                    word.grammar_note = item["grammar_note"]
                    await session.flush()

                # Example
                ex_res = await session.execute(
                    select(Example).where(
                        Example.word_id == word.id,
                        Example.sentence_en == item["sentence_en"],
                    )
                )
                example = ex_res.scalar_one_or_none()
                if example is None:
                    example = Example(
                        word_id=word.id,
                        source_id=source.id,
                        sentence_en=item["sentence_en"],
                        sentence_ru=item["sentence_ru"],
                        cefr_level=item["cefr_level"],
                        is_ai_generated=False,
                    )
                    session.add(example)
                    await session.flush()

                # Cards for all 4 types
                for c_type in ALL_CARD_TYPES:
                    card_res = await session.execute(
                        select(Card).where(
                            Card.user_id == user.id,
                            Card.word_id == word.id,
                            Card.card_type == c_type,
                        )
                    )
                    card = card_res.scalar_one_or_none()
                    if card is None:
                        st = new_card_state()
                        card = Card(
                            user_id=user.id,
                            word_id=word.id,
                            example_id=example.id,
                            card_type=c_type,
                            fsrs_state=st["fsrs_state"],
                            due_at=st["due_at"],
                            stability=st["stability"],
                            difficulty=st["difficulty"],
                            step=st["step"],
                            state=st["state"],
                            reps=0,
                            lapses=0,
                        )
                        session.add(card)
                        await session.flush()
                        total_cards += 1

                lesson_items_export.append({
                    "lemma": word.lemma,
                    "translation_ru": word.translation_ru,
                    "transcription": word.transcription,
                    "part_of_speech": word.part_of_speech,
                    "cefr_level": word.cefr_level,
                    "grammar_note": word.grammar_note,
                    "collocations": word.collocations,
                    "example_en": item["sentence_en"],
                    "example_ru": item["sentence_ru"],
                })

            export_lessons.append({
                "lesson_id": lesson_id,
                "title": title,
                "item_count": len(lesson_items_export),
                "items": lesson_items_export,
            })

        await session.commit()

        # Save to JSON for web client and API
        json_path = Path(__file__).resolve().parent.parent / "app" / "web" / "lessons.json"
        json_path.parent.mkdir(parents=True, exist_ok=True)
        json_path.write_text(json.dumps(export_lessons, ensure_ascii=False, indent=2), encoding="utf-8")

        print(f"Successfully loaded 7 lessons: {total_words} words, {total_cards} FSRS cards created!")
        print(f"Exported lessons to: {json_path}")


if __name__ == "__main__":
    asyncio.run(seed_all_lessons())
